"""Stage r02 — Data dictionary, generated from the contracts. No entry is written by hand here:
meanings live in contracts/descriptions.py, types and allowed values in contracts/schemas.py."""

from __future__ import annotations

import json

from district_evolution import core
from district_evolution.contracts import schemas
from district_evolution.release import TABLES, producing_stage, unit_of

OUT_MD = core.PROJECT_ROOT / "docs" / "data_dictionary.md"
OUT_JSON = core.PROJECT_ROOT / "docs" / "data_dictionary.json"


def allowed(col) -> str:
    parts = []
    for check in col.checks:
        stats = check.statistics or {}
        if "allowed_values" in stats:
            parts.append("one of " + ", ".join(map(str, stats["allowed_values"])))
        elif "min_value" in stats and "max_value" in stats:
            parts.append(f"{stats['min_value']} to {stats['max_value']}")
        elif "pattern" in stats:
            parts.append(f"matches {stats['pattern']}")
        elif "min_value" in stats:
            parts.append(f">= {stats['min_value']}" if check.name == "greater_than_or_equal_to" else f"> {stats['min_value']}")
    return "; ".join(parts)


def main() -> None:
    stages = producing_stage()
    entries = []
    for table in [*TABLES, "release_geometry"]:
        schema = schemas.SCHEMAS[table]
        for name, col in schema.columns.items():
            entries.append({"table": table, "column": name, "dtype": str(col.dtype), "nullable": bool(col.nullable),
                            "unique": bool(col.unique), "unit": unit_of(name), "allowed": allowed(col),
                            "meaning": col.description, "source_stage": stages[table]})
    OUT_JSON.write_text(json.dumps({"pipeline_version": core.PIPELINE_VERSION, "columns": entries}, indent=2,
                                   ensure_ascii=False) + "\n", encoding="utf-8")
    lines = [f"# Data dictionary — pipeline v{core.PIPELINE_VERSION}", "",
             "Generated by `python -m district_evolution.stages.r02_data_dictionary` from the table contracts",
             "(`district_evolution/contracts/`). Do not edit by hand. Areas are geodesic km² on the WGS84 ellipsoid.", ""]
    for table in [*TABLES, "release_geometry"]:
        rows = [e for e in entries if e["table"] == table]
        lines += [f"## `{table}`", "", f"Written by `{rows[0]['source_stage']}`.", "",
                  "| column | type | null | unit | allowed | meaning |", "|---|---|---|---|---|---|"]
        lines += [f"| `{e['column']}` | {e['dtype']} | {'yes' if e['nullable'] else 'no'} | {e['unit']} | "
                  f"{e['allowed'].replace('|', '/')} | {e['meaning']} |" for e in rows]
        lines.append("")
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(entries)} columns in {len(TABLES) + 1} tables")


if __name__ == "__main__":
    main()
