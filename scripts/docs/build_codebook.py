"""Build docs/CODEBOOK.md from docs/codebook.yaml + the pandera contracts.

Descriptions come from docs/codebook.yaml; type, nullability and validation
rules come from scripts/pipeline/schemas.py, so the codebook cannot drift from
what the pipeline enforces. Columns present in a built table but absent from
its contract are listed with type from the data.

  .venv/bin/python scripts/docs/build_codebook.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "pipeline"))
import lib  # noqa: E402
import schemas  # noqa: E402

LOCATIONS = [lib.PRODUCTS_DIR, lib.GOLD_CORE_DIR, lib.GOLD_EVENTS_DIR, lib.GOLD_SPATIAL_DIR]


def load_spec() -> dict:
    return yaml.safe_load((ROOT / "docs" / "codebook.yaml").read_text())


def table_path(name: str, spec: dict) -> Path | None:
    stem = spec.get("file", name)
    for d in LOCATIONS:
        p = d / f"{stem}.parquet"
        if p.exists():
            return p
    return None


def columns(name: str, spec: dict) -> list[str]:
    cols = list(schemas.SCHEMAS[name].columns)
    p = table_path(name, spec)
    if p is not None:
        cols += [c for c in pd.read_parquet(p).columns if c not in cols]
    return cols


def describe(name: str, col: str, spec: dict, common: dict) -> str | None:
    return (spec.get("columns") or {}).get(col) or common.get(col)


def rules(name: str, col: str) -> tuple[str, str]:
    c = schemas.SCHEMAS[name].columns.get(col)
    if c is None:
        return "", ""
    checks = "; ".join(str(ch.error or ch.name) for ch in c.checks)
    return f"{c.dtype}{' (nullable)' if c.nullable else ''}", checks


def main() -> None:
    doc = load_spec()
    common, tables = doc["common"], doc["tables"]
    out = ["# Codebook", "",
           f"Pipeline v{lib.PIPELINE_VERSION}. Generated by `scripts/docs/build_codebook.py` from "
           "`docs/codebook.yaml` (meanings) and `scripts/pipeline/schemas.py` (types and enforced rules). "
           "Do not edit by hand.", ""]
    for name, spec in tables.items():
        p = table_path(name, spec)
        where = p.relative_to(ROOT).as_posix() if p else f"{spec.get('file', name)}.parquet (not built)"
        out += [f"## `{spec.get('file', name)}`", "", f"*Stage {spec['stage']}* · `{where}`", "", spec["meaning"], "",
                "| column | type | rules | meaning |", "|---|---|---|---|"]
        for col in columns(name, spec):
            t, r = rules(name, col)
            d = describe(name, col, spec, common) or "**UNDOCUMENTED**"
            out.append(f"| `{col}` | {t} | {r} | {d} |")
        uniq = schemas.SCHEMAS[name].unique
        if uniq:
            out += ["", f"Unique key: {', '.join(f'`{u}`' for u in uniq)}."]
        out.append("")
    (ROOT / "docs" / "CODEBOOK.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote docs/CODEBOOK.md ({len(tables)} tables)")


if __name__ == "__main__":
    main()
