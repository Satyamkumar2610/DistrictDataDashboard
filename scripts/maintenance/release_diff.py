"""What changed for users between two builds?

Compares an OLD build directory with the current one (both laid out as
data/: gold/core/*.parquet and products/*.parquet), translating old CKs to new
ones with the migration map(s), and writes a markdown report:

  - identities kept / retired (with the CK they merged into) / new
  - products and columns added or removed
  - per census year: how many crosswalk weights moved, by how much, and which
    reference districts' composition changed by more than 1 percentage point
  - administrative areas that changed

A user who harmonized data with the old release reads this to know whether
their results move.

Usage:
  .venv/bin/python scripts/maintenance/release_diff.py --old <dir with gold/ and products/> \
      --old-version 3.0.0 --migration data/reference/ck_migration_v3_to_v4.csv --out docs/release_diffs/x.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "pipeline"))
import lib  # noqa: E402


def ck_map(paths: list[str]) -> dict[str, str]:
    m: dict[str, str] = {}
    for p in paths:
        df = pd.read_csv(p)
        old, new = ("old_ck", "new_ck") if "old_ck" in df.columns else (df.columns[0], df.columns[1])
        df = df[df[new].notna()]
        if "share_of_observations" in df.columns:
            df = df.sort_values("share_of_observations", ascending=False).drop_duplicates(old)
        m.update(dict(zip(df[old], df[new])))
    return m


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--old", required=True, help="directory holding the old build's gold/ and products/")
    ap.add_argument("--old-version", required=True)
    ap.add_argument("--migration", action="append", default=[])
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    old_dir, new_dir = Path(args.old), lib.PROJECT_ROOT / "data"
    mig = ck_map(args.migration)
    tr = lambda s: s.map(lambda c: mig.get(c, c))  # noqa: E731

    o_reg = pd.read_parquet(old_dir / "gold/core/ck_registry.parquet")
    n_reg = pd.read_parquet(new_dir / "gold/core/ck_registry.parquet").set_index("canonical_key")
    o_reg["now"] = tr(o_reg.canonical_key)
    kept = o_reg[(o_reg.canonical_key == o_reg.now) & o_reg.now.isin(n_reg.index)]
    merged = o_reg[(o_reg.canonical_key != o_reg.now) & o_reg.now.isin(n_reg.index)]
    gone = o_reg[~o_reg.now.isin(n_reg.index)]
    new = sorted(set(n_reg.index) - set(o_reg.now))

    lines = [f"# Release diff: v{args.old_version} -> v{lib.PIPELINE_VERSION}", "",
             "Generated by `scripts/maintenance/release_diff.py`. Old CKs are translated with "
             + (", ".join(f"`{Path(p).name}`" for p in args.migration) or "no migration map") + ".", "",
             "## Identities", "",
             f"- kept with the same number: {len(kept)}",
             f"- retired, merged into a continuing identity: {len(merged)}",
             f"- retired, no successor (excluded / non-administrative): {len(gone)}",
             f"- new: {len(new)}", ""]
    if len(merged) or len(gone):
        t = pd.concat([merged.assign(fate="merged into " + merged.now.map(lambda c: f"{c} ({n_reg.latest_name.get(c, '')})")),
                       gone.assign(fate="retired")])
        lines += [t[["canonical_key", "display_name", "fate"]].to_markdown(index=False), ""]

    o_prod = {p.stem for p in (old_dir / "products").glob("*.parquet")}
    n_prod = {p.stem for p in (new_dir / "products").glob("*.parquet")}
    lines += ["## Products", "", f"- added: {', '.join(sorted(n_prod - o_prod)) or 'none'}",
              f"- removed: {', '.join(sorted(o_prod - n_prod)) or 'none'}", ""]
    for p in sorted(o_prod & n_prod):
        oc = set(pd.read_parquet(old_dir / "products" / f"{p}.parquet").columns)
        nc = set(pd.read_parquet(new_dir / "products" / f"{p}.parquet").columns)
        if oc != nc:
            lines.append(f"- `{p}`: columns added {sorted(nc - oc) or '-'}, removed {sorted(oc - nc) or '-'}")
    lines.append("")

    ox = pd.read_parquet(old_dir / "products/crosswalk_to_reference.parquet")
    nx_ = pd.read_parquet(new_dir / "products/crosswalk_to_reference.parquet")
    ox = ox.assign(source_ck=tr(ox.source_ck), target_ck=tr(ox.target_ck)).groupby(
        ["year", "source_ck", "target_ck"], as_index=False)[["share_of_source", "share_of_target"]].sum()
    j = ox.merge(nx_[["year", "source_ck", "target_ck", "share_of_source", "share_of_target"]],
                 on=["year", "source_ck", "target_ck"], how="outer", suffixes=("_old", "_new")).fillna(0.0)
    j["d_src"] = (j.share_of_source_new - j.share_of_source_old).abs()
    j["d_tgt"] = (j.share_of_target_new - j.share_of_target_old).abs()
    comp = j.groupby(["year", "target_ck"]).d_tgt.sum() / 2  # share of the target's composition that moved
    rows = []
    for y, g in j.groupby("year"):
        c = comp.loc[y]
        rows.append({"year": int(y), "pairs": len(g), "weights_moved_gt_0.1pp": int((g.d_src > 0.001).sum()),
                     "max_weight_change_pp": round(100 * g.d_src.max(), 2),
                     "reference_districts_recomposed_gt_1pp": int((c > 0.01).sum())})
    lines += ["## Crosswalk to the reference map", "",
              "A weight is `share_of_source`; a reference district is recomposed when more than 1 percentage "
              "point of its area changed source.", "", pd.DataFrame(rows).to_markdown(index=False), ""]
    worst = comp[comp > 0.01].sort_values(ascending=False).head(25).reset_index()
    if len(worst):
        old_name = o_reg.set_index("canonical_key").latest_name
        worst["target_name"] = [n_reg.latest_name.get(c) or f"{old_name.get(c, c)} (retired in this release)"
                                for c in worst.target_ck]
        worst = worst.rename(columns={"d_tgt": "share_recomposed"})
        worst["share_recomposed"] = worst.share_recomposed.round(4)
        lines += ["Largest recompositions:", "", worst.to_markdown(index=False), ""]

    oa = pd.read_parquet(old_dir / "products/district_area_admin.parquet")
    na = pd.read_parquet(new_dir / "products/district_area_admin.parquet")
    oa = oa.assign(canonical_key=tr(oa.canonical_key)).groupby(["canonical_key", "year"]).area_km2.sum()
    a = pd.concat([oa.rename("old"), na.set_index(["canonical_key", "year"]).area_km2.rename("new")], axis=1)
    moved = a[(a.old.fillna(0) - a.new.fillna(0)).abs() > 0.01]
    lines += ["## Administrative areas", "", f"- (CK, year) areas compared: {len(a)}; changed by > 0.01 km2: {len(moved)}",
              "  (an old observation now belonging to a merged identity, or an excluded feature, shows here).", ""]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
